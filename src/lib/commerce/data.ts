function makeProduct(seed: ProductSeed): Product {
  const numericId = Number.parseInt(seed.id.replace(/\D/g, ""), 10) || 1;
  const coloursWithCodes: Colour[] = seed.colours.map((colour, idx) => ({
    ...colour,
    code: colour.code ?? `${numericId * 100 + idx * 15 + 10} - TYH`,
  }));
  const palette = coloursWithCodes.map((colour) => colour.hex);
  const media: Media[] = seed.media ?? [
    { kind: "skein", palette: palette.slice(0, 3), alt: `${seed.name} yarn skein` },
    {
      kind: "ball",
      palette: [palette[1] ?? palette[0], palette[0], palette[2] ?? palette[0]],
      alt: `${seed.name} yarn wound into a ball`,
    },
    { kind: "texture", palette: palette.slice(0, 2), alt: `${seed.name} fibre texture close-up` },
  ];

  return {
    brand: "TheYarnHook",
    rating: 4.7,
    reviewCount: 38,
    yardage: 180,
    ply: 4,
    needleSize: "4 mm",
    hookSize: "3.5 mm",
    description: "",
    care: ["Hand wash cool", "Dry flat in shade", "Do not bleach"],
    tags: [],
    stock: 24,
    projects: [],
    image:
      seed.image ??
      realProductImages[seed.id] ??
      (seed.collectionId === "desire"
        ? productPlaceholders.desire
        : seed.collectionId === "milka"
          ? productPlaceholders.milka
          : seed.collectionId === "souffle"
            ? productPlaceholders.souffle
            : productPlaceholders["plush-luxe"]),
    ...seed,
    colours: coloursWithCodes,
    weightLabel: weightMeta[seed.weight].label,
    media,
  };
}

